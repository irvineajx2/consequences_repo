#!/usr/bin/env node
/**
 * Scans a ruler's images folder and writes src/ui/imageRegistry.ts: a map from image id (the file
 * name without extension) to a static require(). Metro cannot require computed paths, so this
 * file must be regenerated whenever images are added or removed: `npm run images`.
 *
 * Usage: node scripts/build-image-registry.js [ruler-id]   (default: elizabeth-i)
 */
const fs = require('fs');
const path = require('path');

const ruler = process.argv[2] || 'elizabeth-i';
const root = path.join(__dirname, '..');
const imagesDir = path.join(root, 'assets', 'rulers', ruler, 'images');
const outPath = path.join(root, 'src', 'ui', 'imageRegistry.ts');
const EXTENSIONS = ['.png', '.jpg', '.webp'];

const files = fs.existsSync(imagesDir) ? fs.readdirSync(imagesDir).sort() : [];
const entries = new Map();
for (const file of files) {
  const ext = path.extname(file).toLowerCase();
  if (!EXTENSIONS.includes(ext)) continue;
  const id = path.basename(file, path.extname(file));
  if (entries.has(id)) {
    console.error(`Duplicate image id "${id}": ${entries.get(id)} and ${file}`);
    process.exit(1);
  }
  entries.set(id, file);
}

const relDir = path.relative(path.dirname(outPath), imagesDir).split(path.sep).join('/');
const lines = [...entries].map(
  ([id, file]) => `  ${JSON.stringify(id)}: require(${JSON.stringify(`${relDir}/${file}`)}),`,
);
const source = `// Generated by scripts/build-image-registry.js. Do not edit; run \`npm run images\`.
import type { ImageSourcePropType } from 'react-native';

export const imageRegistry: Readonly<Record<string, ImageSourcePropType>> = {${
  lines.length ? `\n${lines.join('\n')}\n` : ''
}};
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, source);
console.log(`Wrote ${path.relative(root, outPath)} with ${entries.size} image(s)`);
