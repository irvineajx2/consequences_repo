#!/usr/bin/env node
/**
 * Scans every ruler's images folder (assets/rulers/<ruler>/images) and writes
 * src/ui/imageRegistry.ts: for each ruler, a map from image id (the file name without extension) to
 * a static require(). Metro cannot require computed paths, so this file must be regenerated whenever
 * images are added or removed: `npm run images`.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const rulersDir = path.join(root, 'assets', 'rulers');
const outPath = path.join(root, 'src', 'ui', 'imageRegistry.ts');
const EXTENSIONS = ['.png', '.jpg', '.webp'];

const rulers = fs.existsSync(rulersDir)
  ? fs.readdirSync(rulersDir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()
  : [];

/** Every image id a ruler's rules.json and ui.json refer to (as src/game/images.ts and rulerUi.ts read them). */
function referencedIds(ruler) {
  const dataDir = path.join(root, 'src', 'data', 'rulers', ruler);
  const read = (name) => {
    const file = path.join(dataDir, name);
    return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
  };
  const rules = read('rules.json');
  const ui = read('ui.json');
  const ids = new Set();
  if (rules) {
    for (const scene of rules.scenes ?? []) ids.add(scene.image);
    for (const beat of Object.values(rules.beats ?? {})) ids.add(beat.image);
    for (const ending of Object.values(rules.endings ?? {})) ids.add(ending.image);
  }
  if (ui) {
    if (ui.prologue) ids.add(ui.prologue.image);
    for (const era of ui.eras ?? []) {
      ids.add(era.image);
      for (const v of era.variants ?? []) ids.add(v.image);
    }
    if (ui.title) ids.add(ui.title.background);
    if (ui.rulerCard) ids.add(ui.rulerCard.image);
  }
  ids.delete(undefined);
  return ids;
}

const blocks = [];
let total = 0;
for (const ruler of rulers) {
  const imagesDir = path.join(rulersDir, ruler, 'images');
  const files = fs.existsSync(imagesDir) ? fs.readdirSync(imagesDir).sort() : [];
  const entries = new Map();
  for (const file of files) {
    if (!EXTENSIONS.includes(path.extname(file).toLowerCase())) continue;
    const id = path.basename(file, path.extname(file));
    if (entries.has(id)) {
      console.error(`Duplicate image id "${id}" for ${ruler}: ${entries.get(id)} and ${file}`);
      process.exit(1);
    }
    entries.set(id, file);
  }
  const relDir = path.relative(path.dirname(outPath), imagesDir).split(path.sep).join('/');
  const lines = [...entries].map(
    ([id, file]) => `    ${JSON.stringify(id)}: require(${JSON.stringify(`${relDir}/${file}`)}),`,
  );
  blocks.push(`  ${JSON.stringify(ruler)}: {${lines.length ? `\n${lines.join('\n')}\n  ` : ''}},`);
  total += entries.size;
  const missing = [...referencedIds(ruler)].filter((id) => !entries.has(id)).sort();
  console.log(`${ruler}: ${entries.size} image(s)${missing.length ? `, ${missing.length} missing (placeholder shown):` : ''}`);
  if (missing.length) console.log(`  ${missing.join(' ')}`);
}

const source = `// Generated by scripts/build-image-registry.js. Do not edit; run \`npm run images\`.
import type { ImageSourcePropType } from 'react-native';

/** For each ruler folder, its images by id. */
export const imageRegistries: Readonly<Record<string, Readonly<Record<string, ImageSourcePropType>>>> = {
${blocks.join('\n')}
};
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, source);
console.log(`Wrote ${path.relative(root, outPath)} with ${total} image(s)`);

// Achievement badges for the Tudor skin: every PNG in its achievements folder (the @2x and @3x
// copies are picked up by Metro), listed against badges.json.
const badgeDir = path.join(root, 'assets', 'ui', 'skins', 'tudor', 'achievements');
const badgeOut = path.join(root, 'src', 'ui', 'skin', 'tudorBadges.ts');
const badgeFiles = fs.existsSync(badgeDir)
  ? fs.readdirSync(badgeDir).filter((f) => /^[a-z0-9_]+\.png$/.test(f)).sort()
  : [];
const badgeIds = badgeFiles.map((f) => path.basename(f, '.png'));
const badgeLines = badgeFiles.map(
  (f) => `  ${JSON.stringify(path.basename(f, '.png'))}: require(${JSON.stringify(`../../../assets/ui/skins/tudor/achievements/${f}`)}),`,
);
fs.writeFileSync(
  badgeOut,
  `// Generated by scripts/build-image-registry.js. Do not edit; run \`npm run images\`.
import type { ImageSourcePropType } from 'react-native';

/** Achievement badge art by id, plus badge_base (the empty badge). Missing badges show a placeholder. */
export const tudorBadges: Readonly<Record<string, ImageSourcePropType>> = {${badgeLines.length ? `\n${badgeLines.join('\n')}\n` : ''}};
`,
);
const listFile = path.join(badgeDir, 'badges.json');
const expected = fs.existsSync(listFile) ? JSON.parse(fs.readFileSync(listFile, 'utf8')).badges : [];
const missingBadges = expected.filter((id) => !badgeIds.includes(id));
console.log(`badges: ${badgeIds.length} image(s)${missingBadges.length ? `, ${missingBadges.length} missing (placeholder shown):` : ''}`);
if (missingBadges.length) console.log(`  ${missingBadges.join(' ')}`);
