#!/usr/bin/env node
/**
 * Scans every ruler's images folder (assets/rulers/<ruler>/images) and writes
 * src/ui/imageRegistry.ts: for each ruler, a map from image id (the file name without extension) to
 * a static require(). Metro cannot require computed paths, so this file must be regenerated whenever
 * images are added or removed: `npm run images`.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const rulersDir = path.join(root, 'assets', 'rulers');
const outPath = path.join(root, 'src', 'ui', 'imageRegistry.ts');
const EXTENSIONS = ['.png', '.jpg', '.webp'];

const rulers = fs.existsSync(rulersDir)
  ? fs.readdirSync(rulersDir, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()
  : [];

/** Every image id a ruler's rules.json and ui.json refer to (as src/game/images.ts and rulerUi.ts read them). */
function referencedIds(ruler) {
  const dataDir = path.join(root, 'src', 'data', 'rulers', ruler);
  const read = (name) => {
    const file = path.join(dataDir, name);
    return fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : null;
  };
  const rules = read('rules.json');
  const ui = read('ui.json');
  const ids = new Set();
  if (rules) {
    for (const scene of rules.scenes ?? []) {
      ids.add(scene.image);
      for (const v of scene.variants ?? []) if (v.image) ids.add(v.image);
    }
    for (const beat of Object.values(rules.beats ?? {})) ids.add(beat.image);
    for (const ending of Object.values(rules.endings ?? {})) ids.add(ending.image);
  }
  if (ui) {
    if (ui.prologue) ids.add(ui.prologue.image);
    for (const era of ui.eras ?? []) {
      ids.add(era.image);
      for (const v of era.variants ?? []) ids.add(v.image);
    }
    if (ui.title) ids.add(ui.title.background);
    if (ui.rulerCard) ids.add(ui.rulerCard.image);
  }
  ids.delete(undefined);
  return ids;
}

const blocks = [];
let total = 0;
for (const ruler of rulers) {
  const imagesDir = path.join(rulersDir, ruler, 'images');
  const files = fs.existsSync(imagesDir) ? fs.readdirSync(imagesDir).sort() : [];
  const entries = new Map();
  for (const file of files) {
    if (!EXTENSIONS.includes(path.extname(file).toLowerCase())) continue;
    const id = path.basename(file, path.extname(file));
    if (entries.has(id)) {
      console.error(`Duplicate image id "${id}" for ${ruler}: ${entries.get(id)} and ${file}`);
      process.exit(1);
    }
    entries.set(id, file);
  }
  const relDir = path.relative(path.dirname(outPath), imagesDir).split(path.sep).join('/');
  const lines = [...entries].map(
    ([id, file]) => `    ${JSON.stringify(id)}: require(${JSON.stringify(`${relDir}/${file}`)}),`,
  );
  blocks.push(`  ${JSON.stringify(ruler)}: {${lines.length ? `\n${lines.join('\n')}\n  ` : ''}},`);
  total += entries.size;
  const missing = [...referencedIds(ruler)].filter((id) => !entries.has(id)).sort();
  console.log(`${ruler}: ${entries.size} image(s)${missing.length ? `, ${missing.length} missing (placeholder shown):` : ''}`);
  if (missing.length) console.log(`  ${missing.join(' ')}`);
}

const source = `// Generated by scripts/build-image-registry.js. Do not edit; run \`npm run images\`.
import type { ImageSourcePropType } from 'react-native';

/** For each ruler folder, its images by id. */
export const imageRegistries: Readonly<Record<string, Readonly<Record<string, ImageSourcePropType>>>> = {
${blocks.join('\n')}
};
`;
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, source);
console.log(`Wrote ${path.relative(root, outPath)} with ${total} image(s)`);

// Achievement badges for the Tudor skin: every PNG in its achievements folder (the @2x and @3x
// copies are picked up by Metro), listed against badges.json.
const badgeDir = path.join(root, 'assets', 'ui', 'skins', 'tudor', 'achievements');
const badgeOut = path.join(root, 'src', 'ui', 'skin', 'tudorBadges.ts');
const badgeFiles = fs.existsSync(badgeDir)
  ? fs.readdirSync(badgeDir).filter((f) => /^[a-z0-9_]+\.png$/.test(f)).sort()
  : [];
const badgeIds = badgeFiles.map((f) => path.basename(f, '.png'));
const badgeLines = badgeFiles.map(
  (f) => `  ${JSON.stringify(path.basename(f, '.png'))}: require(${JSON.stringify(`../../../assets/ui/skins/tudor/achievements/${f}`)}),`,
);
fs.writeFileSync(
  badgeOut,
  `// Generated by scripts/build-image-registry.js. Do not edit; run \`npm run images\`.
import type { ImageSourcePropType } from 'react-native';

/** Achievement badge art by id, plus badge_base (the empty badge). Missing badges show a placeholder. */
export const tudorBadges: Readonly<Record<string, ImageSourcePropType>> = {${badgeLines.length ? `\n${badgeLines.join('\n')}\n` : ''}};
`,
);
const listFile = path.join(badgeDir, 'badges.json');
// badges.json lists the badges as { id: { file, sourcePx } } (or, earlier, as a list of ids).
const listed = fs.existsSync(listFile) ? JSON.parse(fs.readFileSync(listFile, 'utf8')).badges : [];
const expected = Array.isArray(listed) ? listed : Object.keys(listed ?? {});
const missingBadges = expected.filter((id) => !badgeIds.includes(id));
console.log(`badges: ${badgeIds.length} image(s)${missingBadges.length ? `, ${missingBadges.length} missing (placeholder shown):` : ''}`);
if (missingBadges.length) console.log(`  ${missingBadges.join(' ')}`);

// Avatar art (assets/avatar): a static require for every file the catalogue names. Kept as PNG,
// lossless: lossy compression would put halos round every cut.
const avatarCatalogue = JSON.parse(fs.readFileSync(path.join(root, 'assets', 'avatar', 'avatar.catalogue.json'), 'utf8'));
const avatarOut = path.join(root, 'src', 'ui', 'avatar', 'avatarFiles.ts');
const avatarLines = Object.entries(avatarCatalogue.files)
  .sort(([a], [b]) => (a < b ? -1 : 1))
  .map(([name, f]) => `  ${JSON.stringify(name)}: require(${JSON.stringify(`../../../assets/avatar/${f.file}`)}),`);
fs.mkdirSync(path.dirname(avatarOut), { recursive: true });
fs.writeFileSync(
  avatarOut,
  `// Generated by scripts/build-image-registry.js. Do not edit; run \`npm run images\`.
import type { ImageSourcePropType } from 'react-native';

/** Every avatar image the catalogue names, by name. */
export const avatarFiles: Readonly<Record<string, ImageSourcePropType>> = {\n${avatarLines.join('\n')}\n};
`,
);
console.log(`avatar: ${avatarLines.length} file(s)`);

// Battles: each battle's images (assets/battles/<id>/images, ids as battle.json names them), the
// mode-wide icons and banner (assets/ui/skins/tudor/battles), and each battle's sector positions:
// the art chat's file (named by battle.json images.sectorPositions) in assets/battles/<id>/ or
// content/battles/<id>/ once it arrives, otherwise the placeholder. Missing images show placeholders.
const battlesContent = path.join(root, 'content', 'battles');
const battlesAssets = path.join(root, 'assets', 'battles');
const battleSkin = path.join(root, 'assets', 'ui', 'skins', 'tudor', 'battles');
const battleOut = path.join(root, 'src', 'ui', 'battle', 'battleArt.ts');
const battleIds = fs.existsSync(battlesContent)
  ? fs.readdirSync(battlesContent, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()
  : [];
const rel = (file) => path.relative(path.dirname(battleOut), file).split(path.sep).join('/');
const battleBlocks = [];
const sectorBlocks = [];
for (const id of battleIds) {
  const data = JSON.parse(fs.readFileSync(path.join(battlesContent, id, 'battle.json'), 'utf8'));
  const dir = path.join(battlesAssets, id, 'images');
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => EXTENSIONS.includes(path.extname(f).toLowerCase())).sort() : [];
  const lines = files.map((f) => `    ${JSON.stringify(path.basename(f, path.extname(f)))}: require(${JSON.stringify(rel(path.join(dir, f)))}),`);
  battleBlocks.push(`  ${JSON.stringify(id)}: {${lines.length ? `\n${lines.join('\n')}\n  ` : ''}},`);
  const im = data.images;
  const wanted = [im.card, ...Object.values(im.maps), ...Object.values(im.scenes), ...Object.values(im.endings), ...Object.values(im.unlockables)];
  const have = new Set(files.map((f) => path.basename(f, path.extname(f))));
  const missing = wanted.filter((w) => !have.has(w));
  const name = im.sectorPositions;
  const real = [path.join(battlesAssets, id, name), path.join(battlesContent, id, name)].find((f) => fs.existsSync(f));
  const sectors = real ?? path.join(battlesContent, id, 'map_sectors.placeholder.json');
  sectorBlocks.push(`  ${JSON.stringify(id)}: require(${JSON.stringify(rel(sectors))}),`);
  console.log(`battle ${id}: ${files.length} image(s)${missing.length ? `, ${missing.length} missing (placeholder shown): ${missing.join(' ')}` : ''}; sector positions ${real ? `from ${path.relative(root, real)}` : 'placeholder'}`);
}
const iconDir = path.join(battleSkin, 'icons');
const iconFiles = fs.existsSync(iconDir) ? fs.readdirSync(iconDir).filter((f) => /^[a-z0-9_]+\.png$/.test(f)).sort() : [];
const iconLines = iconFiles.map((f) => `  ${JSON.stringify(path.basename(f, '.png'))}: require(${JSON.stringify(rel(path.join(iconDir, f)))}),`);
const banner = fs.existsSync(battleSkin) ? fs.readdirSync(battleSkin).find((f) => /^BMODE1\.(png|jpg|webp)$/.test(f)) : undefined;
fs.mkdirSync(path.dirname(battleOut), { recursive: true });
fs.writeFileSync(
  battleOut,
  `// Generated by scripts/build-image-registry.js. Do not edit; run \`npm run images\`.
import type { ImageSourcePropType } from 'react-native';

/** Each battle's images by id (cards, maps, scenes, endings, unlockables). */
export const battleImages: Readonly<Record<string, Readonly<Record<string, ImageSourcePropType>>>> = {
${battleBlocks.join('\n')}
};

/** Battle mode icons (moves, medals, the commander and sector states) by name. */
export const battleIcons: Readonly<Record<string, ImageSourcePropType>> = {${iconLines.length ? `\n${iconLines.join('\n')}\n` : ''}};

/** The battle mode banner, if drawn. */
export const battleBanner: ImageSourcePropType | null = ${banner ? `require(${JSON.stringify(rel(path.join(battleSkin, banner)))})` : 'null'};

/** Each battle's sector positions on its maps (the art chat's file, or the placeholder). */
export const battleSectorFiles: Readonly<Record<string, unknown>> = {
${sectorBlocks.join('\n')}
};
`,
);
console.log(`battle icons: ${iconFiles.length} image(s)${banner ? ', banner' : ', no banner'}`);
