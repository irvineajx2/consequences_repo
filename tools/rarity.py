"""Ending rarity for one ruler: the share of history-leaning runs (55% historical choices) reaching each
ending, and its tier. Written to src/data/rulers/<ruler>/rarity.json; the game never computes rarity.

Tiers: Common 5% or more; Uncommon 1% to 5%; Rare 0.1% to 1%; Epic 0.01% to 0.1%; Legendary below
0.01%, or reached in fewer than 10 simulated runs (noted in the output).
Also measured, for achievement rarity: the share of runs that visit any branch scene, and of runs
that match every decision.

Usage (from the repo root): npm run rarity -- <ruler-id> [RUNS]   (default 1,000,000)
"""
import json, os, random, sys
from collections import Counter
from multiprocessing import Pool

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from engine import Engine  # noqa: E402

LEAN = 0.55
WORKERS = 4
MIN_RUNS = 10
TIERS = [(0.05, "common"), (0.01, "uncommon"), (0.001, "rare"), (0.0001, "epic")]


def tier(share, runs):
    if runs < MIN_RUNS: return "legendary"
    for at_least, name in TIERS:
        if share >= at_least: return name
    return "legendary"


def worker(args):
    rules_path, seed, n = args
    E = Engine(rules_path); rng = random.Random(seed)
    endings = Counter(); branch = 0; faithful = 0
    for _ in range(n):
        st = E.start(); any_branch = False; all_hist = True
        for i, sc in enumerate(E.scenes):
            mode, opts = E.options(i, st)
            if mode != "skip":
                h = [o for o in opts if o["historical"]]
                o = h[0] if h and rng.random() < LEAN else rng.choice([x for x in opts if not x["historical"]] or opts)
                if sc.get("branch"): any_branch = True
                if mode != "auto" and not o["historical"]: all_hist = False
                st, end = E.choose(i, st, o)
                if end: break
            st, end, _, _ = E.resolve(i, st)
            if end: break
        endings[end] += 1; branch += any_branch; faithful += all_hist
    return endings, branch, faithful


def main():
    ruler = sys.argv[1]
    runs = int(sys.argv[2]) if len(sys.argv) > 2 else 1_000_000
    rules_path = os.path.join(ROOT, "src", "data", "rulers", ruler, "rules.json")
    E = Engine(rules_path)
    per = runs // WORKERS
    with Pool(WORKERS) as pool:
        parts = pool.map(worker, [(rules_path, 1000 + k, per) for k in range(WORKERS)])
    total = per * WORKERS
    endings = sum((p[0] for p in parts), Counter())
    out = {
        "_note": "Generated by `npm run rarity -- " + ruler + "` (tools/rarity.py). Do not edit by hand.",
        "policy": "history-leaning, 55% historical choices",
        "runs": total,
        "rulesVersion": E.d["version"],
        "endings": {},
        "anyBranchShare": sum(p[1] for p in parts) / total,
        "allHistoricalShare": sum(p[2] for p in parts) / total,
    }
    notes = []
    for e in E.d["endings"]:
        n = endings[e]; share = n / total
        out["endings"][e] = {"share": share, "tier": tier(share, n), "runs": n}
        if n < MIN_RUNS: notes.append(f"{e}: reached in only {n} of {total:,} runs, so Legendary")
    path = os.path.join(ROOT, "src", "data", "rulers", ruler, "rarity.json")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, indent=2); f.write("\n")
    print(f"{ruler}: {total:,} history-leaning runs -> {os.path.relpath(path, ROOT)}")
    for e, r in sorted(out["endings"].items(), key=lambda x: -x[1]["share"]):
        print(f"  {e:24} {r['share'] * 100:9.4f}%  {r['tier']}")
    print(f"  any branch scene: {out['anyBranchShare'] * 100:.3f}%; every decision matched: {out['allHistoricalShare'] * 100:.5f}%")
    for n in notes: print("  NOTE " + n)


if __name__ == "__main__":
    main()
